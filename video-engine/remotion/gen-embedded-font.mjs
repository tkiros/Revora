// One-off generator: inline the Plus Jakarta Sans latin weights (500/700/800) as base64
// data URIs so the Remotion render has ZERO runtime font fetch. A network fetch to the
// webpack-serve can stall under memory pressure and time out the font delayRender; a data
// URI is decoded from the bundle in-memory and can't stall. Re-run if the weights change:
//   node video-engine/remotion/gen-embedded-font.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const filesDir = path.join(dir, "../../node_modules/@fontsource/plus-jakarta-sans/files");
const weights = [500, 700, 800];

const faces = weights.map((w) => {
  const woff2 = fs.readFileSync(path.join(filesDir, `plus-jakarta-sans-latin-${w}-normal.woff2`));
  const b64 = woff2.toString("base64");
  return `@font-face {
  font-family: 'Plus Jakarta Sans';
  font-style: normal;
  font-weight: ${w};
  font-display: block;
  src: url(data:font/woff2;base64,${b64}) format('woff2');
}`;
}).join("\n");

const header = `/* GENERATED by gen-embedded-font.mjs — do not edit by hand.
 * Plus Jakarta Sans latin weights 500/700/800 inlined as base64 so the render has no
 * runtime font fetch (a stalled fetch under memory pressure was timing out the font
 * delayRender). font-display:block holds the fallback until the (instant) inline font
 * is ready, so text never flashes in Arial. Regenerate: node video-engine/remotion/gen-embedded-font.mjs */\n`;

fs.writeFileSync(path.join(dir, "plus-jakarta-embedded.css"), header + faces + "\n");
console.log("wrote plus-jakarta-embedded.css");
